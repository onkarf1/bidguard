/**
 * Looks for AI-generation provenance inside an image file's raw bytes (works in browser and Node).
 * Finding one is strong evidence; finding none proves nothing (metadata is easy to strip).
 *  - IPTC DigitalSourceType "trainedAlgorithmicMedia" (Google, Meta, Adobe, OpenAI write this)
 *  - C2PA Content Credentials naming a generative tool
 *  - Generator fingerprints: Stable Diffusion/A1111 "parameters", ComfyUI workflows, tool names
 */
const GENERATORS: [RegExp, string][] = [
  [/midjourney/i, "Midjourney"],
  [/DALL[·\-\s]?E/i, "DALL·E"],
  [/gpt-?image|chatgpt|openai/i, "OpenAI"],
  [/adobe firefly|firefly/i, "Adobe Firefly"],
  [/stable[\s_-]?diffusion|sdxl|automatic1111/i, "Stable Diffusion"],
  [/comfyui/i, "ComfyUI"],
  [/novelai/i, "NovelAI"],
  [/leonardo\.ai/i, "Leonardo.Ai"],
  [/ideogram/i, "Ideogram"],
  [/flux\.1|black forest labs/i, "FLUX"],
  [/google imagen|imagen [234]|gemini image/i, "Google Imagen"],
];

export function scanProvenance(bytes: Uint8Array): string[] {
  // latin1 keeps every byte as one char, so ASCII metadata is searchable.
  let text = "";
  const CHUNK = 0x8000;
  for (let i = 0; i < bytes.length; i += CHUNK) text += String.fromCharCode.apply(null, Array.from(bytes.subarray(i, i + CHUNK)));
  const found = new Set<string>();
  if (/compositeWithTrainedAlgorithmicMedia/.test(text)) found.add("IPTC tag: partly generated by AI");
  else if (/trainedAlgorithmicMedia/.test(text)) found.add("IPTC tag: generated by AI");
  if (/parameters\0[\s\S]{0,4000}Steps: \d+[\s\S]{0,400}Sampler:/.test(text)) found.add("Stable Diffusion generation settings embedded");
  if (/"class_type"\s*:/.test(text) && /\b(prompt|workflow)\0/.test(text)) found.add("ComfyUI workflow embedded");
  const hasC2pa = /c2pa/i.test(text);
  // Only look for tool names inside metadata-ish regions, to avoid matching random pixel bytes.
  const meta = text.slice(0, 600_000);
  for (const [re, name] of GENERATORS) {
    if (re.test(meta)) found.add(hasC2pa ? `Content Credentials name ${name}` : `Metadata mentions ${name}`);
  }
  return Array.from(found).slice(0, 8);
}

/** Output sizes typical of image generators (weak signal on its own). */
const GEN_SIZES = new Set(["1024x1024", "1792x1024", "1024x1792", "1536x1024", "1024x1536", "832x1216", "1216x832", "896x1152", "1152x896", "2048x2048", "512x512", "768x768", "1344x768", "768x1344"]);
export const isGeneratorSize = (w?: number, h?: number) => !!w && !!h && GEN_SIZES.has(`${w}x${h}`);
